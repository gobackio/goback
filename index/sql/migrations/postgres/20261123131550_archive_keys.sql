-- Name archives by a numeric key: "archives"."id" becomes "name" and a new
-- identity "id" keys the table
ALTER TABLE "archives" RENAME COLUMN "id" TO "name";
ALTER TABLE "archives" ADD COLUMN "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY;
-- Rebuild "objects" keyed by the archive's number, fixed-width columns first
CREATE TABLE "objects_new" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "archive_id" bigint NOT NULL, "start" bigint NOT NULL, "length" bigint NOT NULL, "type" bigint NOT NULL, "carried_time" bigint NULL, "carried_offset" bigint NULL, "incomplete" boolean NOT NULL DEFAULT false, "ref" bytea NOT NULL);
INSERT INTO "objects_new" ("id", "archive_id", "start", "length", "type", "carried_time", "carried_offset", "incomplete", "ref") SELECT o."id", a."id", o."start", o."length", o."type", o."carried_time", o."carried_offset", o."incomplete", o."ref" FROM "objects" o JOIN "archives" a ON a."name" = o."archive_id";
SELECT setval(pg_get_serial_sequence('"objects_new"', 'id'), coalesce(max("id"), 0) + 1, false) FROM "objects_new";
DROP TABLE "objects";
ALTER TABLE "objects_new" RENAME TO "objects";
ALTER SEQUENCE "objects_new_id_seq" RENAME TO "objects_id_seq";
ALTER TABLE "objects" ADD PRIMARY KEY ("id");
ALTER TABLE "archives" DROP CONSTRAINT "archives_pkey", ADD PRIMARY KEY ("id");
CREATE UNIQUE INDEX "archives_name_key" ON "archives" ("name");
ALTER TABLE "objects" ADD CONSTRAINT "objects_archives_objects" FOREIGN KEY ("archive_id") REFERENCES "archives" ("id") ON UPDATE NO ACTION ON DELETE CASCADE, ADD CONSTRAINT "objects_ref_width" CHECK (length(ref) = 32);
CREATE UNIQUE INDEX "objects_archive_ref" ON "objects" ("archive_id", "ref");
CREATE INDEX "objects_ref" ON "objects" USING HASH ("ref");
CREATE INDEX "objects_tombstones" ON "objects" ("ref") WHERE (type = 5);
CREATE INDEX "objects_commits" ON "objects" ("ref") WHERE (type = 1);
-- Vacuum "objects" after 1% of its rows change, so space a collection's
-- rewrites free is reused before the table grows
ALTER TABLE "objects" SET (autovacuum_vacuum_scale_factor = 0.01, autovacuum_vacuum_insert_scale_factor = 0.01);
